    /// <summary>"auto" (既定) / "ja" / "en"。AppSettings.Languageから設定される。</summary>
    public static string Override { get; set; } = "auto";

    public static event Action? Changed;

    public static bool IsEnglish()
    {
        if (Override == "ja") return false;
        if (Override == "en") return true;
        return !CultureInfo.CurrentUICulture.Name.StartsWith("ja");
    }

    public static string T(string key, params object[] args)
    {
        if (!Entries.TryGetValue(key, out var e)) return key;
        var fmt = IsEnglish() ? e.En : e.Ja;
        return args.Length == 0 ? fmt : string.Format(fmt, args);
    }

    public static void SetOverride(string value)
    {
        if (Override == value) return;
        Override = value;
        Changed?.Invoke();
    }
